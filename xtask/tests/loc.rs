#![allow(clippy::unwrap_used, clippy::expect_used)]

#[test]
fn counts_code_excluding_comments_test_files_and_generated() {
    let d = tempfile::tempdir().unwrap();
    std::fs::create_dir_all(d.path().join("src/tests")).unwrap();
    std::fs::write(
        d.path().join("src/lib.rs"),
        "// doc\n\nfn a() {}\n/* block\n still */\nfn b() {}\n#[cfg(test)]\nmod tests {}\n",
    )
    .unwrap();
    std::fs::write(d.path().join("src/tests.rs"), "fn t() {}\n").unwrap();
    std::fs::write(d.path().join("src/tests/x.rs"), "fn t() {}\n").unwrap();
    std::fs::write(
        d.path().join("src/generated.rs"),
        "// @generated by cargo xtask gen. Do not edit.\nstruct S;\n",
    )
    .unwrap();
    let l = xtask::loc::count(d.path());
    assert_eq!((l.code, l.generated), (4, 1));
}

#[test]
fn counts_code_after_nested_block_comments() {
    let d = tempfile::tempdir().unwrap();
    std::fs::create_dir(d.path().join("src")).unwrap();
    std::fs::write(
        d.path().join("src/lib.rs"),
        "/* outer /* nested */\n end */ fn a() {}\nlet url = \"https://example.com\";\n",
    )
    .unwrap();
    assert_eq!(xtask::loc::count(d.path()).code, 2);
}

#[test]
fn enforces_budget_boundaries_and_generated_crate_placement() {
    use xtask::{
        deps::Policy,
        loc::{Loc, exceeds_budget},
    };
    let policy = Policy::from_toml(include_str!("../crates.toml")).unwrap();
    for (name, max) in [
        ("pacer-foundation", 2000),
        ("pacer", 500),
        ("pacer-server", 12000),
    ] {
        let rules = &policy.crates[name];
        assert!(!exceeds_budget(
            &policy.limits,
            rules,
            name,
            &Loc {
                code: max,
                generated: 0
            }
        ));
        assert!(exceeds_budget(
            &policy.limits,
            rules,
            name,
            &Loc {
                code: max + 1,
                generated: 0
            }
        ));
    }
    let generated = &policy.crates["pacer-client-protocol"];
    assert!(!exceeds_budget(
        &policy.limits,
        generated,
        "pacer-client-protocol",
        &Loc {
            code: 1,
            generated: 10000
        }
    ));
    assert!(exceeds_budget(
        &policy.limits,
        generated,
        "pacer-client-protocol",
        &Loc {
            code: 1,
            generated: 10001
        }
    ));
    assert!(exceeds_budget(
        &policy.limits,
        &policy.crates["pacer-server"],
        "pacer-server",
        &Loc {
            code: 0,
            generated: 1
        }
    ));
}
