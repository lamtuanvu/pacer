#![allow(clippy::unwrap_used)]
use super::*;
use crate::r#gen::emit;
use std::process::Command;

fn temp_input(dir: &Path, json: &str) -> PathBuf {
    let input = dir.join("freshness.constants.json");
    fs::write(&input, json).unwrap();
    input
}

/// The pinned toolchain's rustfmt, so the test's expected text is the real output.
fn formatting_works() -> bool {
    Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

#[test]
fn generates_screaming_snake_constants() {
    if !formatting_works() {
        return; // rustfmt is missing; the real run reports it.
    }
    let dir = tempfile::tempdir().unwrap();
    let input = temp_input(
        dir.path(),
        r#"{"windowCapShortMaxLengthS":21600,"exhaustedPct":97}"#,
    );
    assert_eq!(
        generate(&input).unwrap(),
        concat!(
            "// @generated by cargo xtask gen. Do not edit.\n",
            "//! Usage freshness thresholds shared with `src/usage/freshness.ts` (ADR 0030 decision 5).\n",
            "\n",
            "#![allow(clippy::all, clippy::unwrap_used, clippy::expect_used, missing_docs)]\n",
            "\n",
            "pub const WINDOW_CAP_SHORT_MAX_LENGTH_S: i64 = 21600;\n",
            "pub const EXHAUSTED_PCT: f64 = 97.0;\n",
        )
    );
}

#[test]
fn rejects_keys_without_the_s_or_pct_suffix() {
    let dir = tempfile::tempdir().unwrap();
    let input = temp_input(dir.path(), r#"{"windowCapDays":7}"#);
    assert!(generate(&input).unwrap_err().contains("S (seconds) or Pct"));
}

#[test]
fn rejects_non_integral_seconds() {
    let dir = tempfile::tempdir().unwrap();
    let input = temp_input(dir.path(), r#"{"authLifetimeS":72.5}"#);
    assert!(
        generate(&input)
            .unwrap_err()
            .contains("whole number of seconds")
    );
}

/// The same stale-file check the schema targets use: `--check` fails when the
/// generated file is out of date, and is silent when it matches.
#[test]
fn check_mode_detects_drift() {
    if !formatting_works() {
        return;
    }
    let dir = tempfile::tempdir().unwrap();
    let input = temp_input(dir.path(), r#"{"nearLimitPct":90}"#);
    let out = dir.path().join("freshness.rs");
    let code = generate(&input).unwrap();

    fs::write(&out, &code).unwrap();
    let mut stale = Vec::new();
    emit(&out, Ok(code.clone()), true, &mut stale).unwrap();
    assert!(stale.is_empty(), "a fresh file is not stale");

    fs::write(&out, "// hand-edited\n").unwrap();
    let mut stale = Vec::new();
    emit(&out, Ok(code.clone()), true, &mut stale).unwrap();
    assert_eq!(stale, vec![out.display().to_string()]);
}
