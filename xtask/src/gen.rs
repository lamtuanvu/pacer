//! Deterministic Rust protocol generation from the checked-in schema bundles.
use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

const HEADER: &str = "// @generated by cargo xtask gen. Do not edit.\n";

pub fn targets() -> [(PathBuf, PathBuf); 2] {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap_or(Path::new("."));
    [
        (
            root.join("docs/protocol.schema.json"),
            root.join("crates/client-protocol/src/generated.rs"),
        ),
        (
            root.join("docs/plugin-protocol.schema.json"),
            root.join("crates/plugin-protocol/src/generated.rs"),
        ),
    ]
}

pub fn generate(schema_path: &Path) -> Result<String, String> {
    let text =
        fs::read_to_string(schema_path).map_err(|e| format!("{}: {e}", schema_path.display()))?;
    let value: serde_json::Value = serde_json::from_str(&text).map_err(|e| e.to_string())?;
    // The M0 plugin bundle stores its protocol version in the title.
    let version = value
        .get("version")
        .and_then(|v| v.as_str())
        .or_else(|| {
            value
                .get("title")
                .and_then(|v| v.as_str())?
                .strip_prefix("pacer plugin protocol ")
        })
        .filter(|v| !v.is_empty())
        .ok_or("schema has no protocol version")?;
    let schema: schemars::schema::RootSchema =
        serde_json::from_str(&text).map_err(|e| e.to_string())?;
    let mut space =
        typify::TypeSpace::new(typify::TypeSpaceSettings::default().with_struct_builder(false));
    space.add_root_schema(schema).map_err(|e| e.to_string())?;
    let file: syn::File = syn::parse2(space.to_stream()).map_err(|e| e.to_string())?;
    rustfmt(&format!(
        "{HEADER}#![allow(clippy::all, clippy::unwrap_used, clippy::expect_used, missing_docs)]\n\npub const VERSION: &str = {version:?};\n\n{}",
        prettyplease::unparse(&file)
    ))
}

/// Format with the pinned toolchain's rustfmt so `cargo fmt --check` accepts generated files.
fn rustfmt(code: &str) -> Result<String, String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt: no stdin")?
        .write_all(code.as_bytes())
        .map_err(|e| format!("rustfmt: {e}"))?;
    let out = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !out.status.success() {
        return Err("rustfmt failed on generated code".into());
    }
    String::from_utf8(out.stdout).map_err(|e| format!("rustfmt: {e}"))
}

pub fn run(check: bool) -> Result<(), String> {
    let mut stale = Vec::new();
    for (schema, out) in targets() {
        let code =
            generate(&schema).map_err(|e| format!("xtask gen: {}: {e}", schema.display()))?;
        if check {
            if fs::read_to_string(&out).ok().as_deref() != Some(&code) {
                stale.push(out.display().to_string());
            }
        } else {
            fs::write(&out, code).map_err(|e| format!("{}: {e}", out.display()))?;
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!("stale: {}\nrun: cargo xtask gen", stale.join(", ")))
    }
}
