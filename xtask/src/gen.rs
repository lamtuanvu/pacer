pub fn generate(schema_path: &Path) -> Result<String, String> {
    generate_area(schema_path, "core")
}

/// Parameter areas have separate compilation and generated-size budgets.
pub fn generate_for(schema_path: &Path, output_path: &Path) -> Result<String, String> {
    let area = output_path
        .parent()
        .and_then(Path::parent)
        .and_then(Path::file_name)
        .and_then(|name| name.to_str())
        .unwrap_or("core");
    generate_area(schema_path, area)
}

fn generate_area(schema_path: &Path, area: &str) -> Result<String, String> {
    let policy = area == "plugin-policy-protocol";
    let text =
        fs::read_to_string(schema_path).map_err(|e| format!("{}: {e}", schema_path.display()))?;
    let mut value: serde_json::Value = serde_json::from_str(&text).map_err(|e| e.to_string())?;
    if value.get("title").and_then(|v| v.as_str()) == Some("pacer client protocol") {
        let defs = value
            .get_mut("$defs")
            .and_then(|v| v.as_object_mut())
            .ok_or("client schema has no definitions")?;
        let agent_control = |name: &str| {
            name.starts_with("ClientControl")
                || name.starts_with("ApiList")
                || name.starts_with("ApiDescribe")
        };
        defs.retain(|name, _| match area {
            "session-protocol" => name.starts_with("Session"),
            "dispatch-protocol" => name.starts_with("Dispatch"),
            "client-control-protocol" => agent_control(name),
            "limits-protocol" => name.starts_with("Limits"),
            _ => {
                !name.starts_with("Session")
                    && !name.starts_with("Dispatch")
                    && !name.starts_with("Limits")
                    && !agent_control(name)
            }
        });
    }
    if value
        .get("title")
        .and_then(|v| v.as_str())
        .is_some_and(|title| title.starts_with("pacer plugin protocol "))
    {
        let defs = value
            .get_mut("$defs")
            .and_then(|v| v.as_object_mut())
            .ok_or("plugin schema has no definitions")?;
        defs.retain(|name, _| {
            let agent = name.starts_with("agentSession.");
            let dispatch = name.starts_with("observation.") || name.starts_with("decision.");
            let hosts = name.starts_with("hostRunner.") || name.starts_with("capability.hosts.");
            let execution =
                name.starts_with("executor.") || name.starts_with("capability.process.");
            match area {
                "plugin-agent-protocol" => agent,
                "plugin-dispatch-protocol" => dispatch,
                "plugin-hosts-protocol" => hosts,
                "plugin-exec-protocol" => execution,
                _ => {
                    !agent && !dispatch && !hosts && !execution && policy_definition(name) == policy
                }
            }
        });
    }
    // The M0 plugin bundle stores its protocol version in the title.
    let version = value
        .get("version")
        .and_then(|v| v.as_str())
        .or_else(|| {
            value
                .get("title")
                .and_then(|v| v.as_str())?
                .strip_prefix("pacer plugin protocol ")
        })
        .filter(|v| !v.is_empty())
        .ok_or("schema has no protocol version")?
        .to_owned();
    let plugin = value
        .get("title")
        .and_then(|v| v.as_str())
        .is_some_and(|title| title.starts_with("pacer plugin protocol "));
    let schema: schemars::schema::RootSchema =
        serde_json::from_value(value.clone()).map_err(|e| e.to_string())?;
    let mut space =
        typify::TypeSpace::new(typify::TypeSpaceSettings::default().with_struct_builder(false));
    space.add_root_schema(schema).map_err(|e| e.to_string())?;
    let mut file: syn::File = syn::parse2(space.to_stream()).map_err(|e| e.to_string())?;
    file.items.retain(|item| !redundant_impl(item));
    if policy {
        policy_bounds::apply(&mut file, &value)?;
        policy_collections::apply(&mut file, &value)?;
        policy_metadata::apply(&mut file, &value)?;
    }
    if plugin {
        validators::share_string_validators(&mut file)?;
    }
    rustfmt(&format!(
        "{HEADER}#![allow(clippy::all, clippy::unwrap_used, clippy::expect_used, missing_docs)]\n\npub const VERSION: &str = {version:?};\n\n{}",
        prettyplease::unparse(&file)
    ))
}

/// New policy/observation contracts are an independent generated protocol area.
/// Existing lifecycle metadata stays in the original crate to preserve its public types.
fn policy_definition(name: &str) -> bool {
    name == "pluginMetadata"
        || name.starts_with("pluginMetadata_")
        || name.starts_with("readOwnerMetadata")
        || name.starts_with("policy.before.")
        || name.starts_with("policyEvent")
        || name.starts_with("capability.tasks.")
        || name.starts_with("capability.events.")
}

/// Conversions typify emits that only repeat another impl: `From<&T> for T` (a clone) and
/// `TryFrom<String>` / `TryFrom<&String>` (a `FromStr` call). Dropping them keeps the generated
/// crates inside the CRATE-3 line budget and cuts their compile time; `FromStr`,
/// `TryFrom<&str>` and serde stay.
fn redundant_impl(item: &syn::Item) -> bool {
    let syn::Item::Impl(imp) = item else {
        return false;
    };
    let Some((_, path, _)) = &imp.trait_ else {
        return false;
    };
    let Some(last) = path.segments.last() else {
        return false;
    };
    let syn::PathArguments::AngleBracketed(args) = &last.arguments else {
        return false;
    };
    let Some(syn::GenericArgument::Type(arg)) = args.args.first() else {
        return false;
    };
    let arg = arg.to_token_stream().to_string().replace(' ', "");
    let self_ty = imp.self_ty.to_token_stream().to_string().replace(' ', "");
    match last.ident.to_string().as_str() {
        "From" => arg == format!("&{self_ty}"),
        "TryFrom" => arg == "::std::string::String" || arg == "&::std::string::String",
        _ => false,
    }
}

/// Format with the pinned toolchain's rustfmt so `cargo fmt --check` accepts generated files.
fn rustfmt(code: &str) -> Result<String, String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt: no stdin")?
        .write_all(code.as_bytes())
        .map_err(|e| format!("rustfmt: {e}"))?;
    let out = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !out.status.success() {
        return Err("rustfmt failed on generated code".into());
    }
    String::from_utf8(out.stdout).map_err(|e| format!("rustfmt: {e}"))
}

pub fn run(check: bool) -> Result<(), String> {
    let mut stale = Vec::new();
    for (schema, out) in targets() {
        let code = generate_for(&schema, &out)
            .map_err(|e| format!("xtask gen: {}: {e}", schema.display()))?;
        if check {
            if fs::read_to_string(&out).ok().as_deref() != Some(&code) {
                stale.push(out.display().to_string());
            }
        } else {
            fs::write(&out, code).map_err(|e| format!("{}: {e}", out.display()))?;
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!("stale: {}\nrun: cargo xtask gen", stale.join(", ")))
    }
}
