/** Fixed builds: the last pre-feature release, and two feature builds of this checkout. */
export const UPGRADE_BUILDS = {
  prefeature: { version: "0.11.0", ref: "v0.11.0" },
  baseline: { version: "0.13.0", ref: null },
  candidate: { version: "0.13.1", ref: null },
} as const;
export type UpgradeBuild = keyof typeof UPGRADE_BUILDS;
interface UpgradeRecord { schema: 1; policy: NativeFixture; builds: Record<UpgradeBuild, { path: string; sha256: string }>; installed: boolean }

/** Upgrade fixtures replace the sandbox service, so the sandbox must be unseeded (real agents) and stopped. */
export function upgradeRoot(session: Session, platform: string = process.platform): string {
  const expected = join(liveRoot, validId(session.id));
  if (session.root !== expected || session.seed !== undefined || !session.stopped || session.innerPort === undefined)
    throw Error("live upgrade needs an unseeded sandbox stopped with: bun run live down --id <id> --keep");
  if (platform !== "darwin") throw Error("live upgrade fixtures need macOS; run the Linux scenarios by hand (docs/testing/live-validation.md)");
  return join(expected, "upgrade");
}

/** A compiled fixture lease: its service label, home and port are fixed at build time. */
export function upgradePolicy(session: Session, nonce: string, uid: number): NativeFixture {
  const root = join(session.root, "ota");
  return parseNativeFixture(JSON.stringify({ schema: 1, root, nonce, home: join(session.root, "home"), port: session.innerPort,
    currentApp: join(root, "current.app"), serviceLabel: `com.pacer.live.${nonce}.service`, recoveryLabel: `com.pacer.live.${nonce}.recovery`, uid }));
}

/** Generated by this checkout and labelled for the fixture job; any non-fixture label is refused. */
export function fixturePlist(policy: NativeFixture, binary: string): string {
  if (policy.serviceLabel === LABEL || !policy.serviceLabel.startsWith("com.pacer.live.")) throw Error("Refusing a non-fixture service label");
  const ctx = makeCtx({ home: policy.home, pacerHome: policy.home, env: { PATH: process.env.PATH ?? "/usr/bin:/bin", PACER_BIN: binary, PACER_PORT: String(policy.port) } });
  return plist(ctx, [binary], policy.serviceLabel);
}

/** The single-binary release layout `pacer update` reads from PACER_RELEASE_BASE. */
export function writeFeed(feed: string, version: string, bytes: Uint8Array): void {
  const target = hostTarget();
  if (!target) throw Error("Unsupported platform");
  const file = assetFile(target), dir = join(feed, version);
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  writeFileSync(join(dir, file), bytes, { mode: 0o600 });
  writeFileSync(join(dir, "manifest.json"), JSON.stringify({ version, assets: [{ os: target.os, arch: target.arch, file, size: bytes.length, sha256: sha256Hex(bytes) }] }), { mode: 0o600 });
  writeFileSync(join(dir, "SHA256SUMS"), `${sha256Hex(bytes)}  ${file}\n`, { mode: 0o600 });
}

/** Release 0.11.0 targets the real launchd label from its own service code, so it must never run those paths. */
export function guardPacerArgs(installed: UpgradeBuild, args: string[]): void {
  const [cmd] = args;
  if (["service", "uninstall", "install", "init", "setup", "open"].includes(cmd ?? "")) throw Error(`live upgrade refuses "${cmd}"; use live upgrade start, install, kickstart or cleanup`);
  if (cmd === "update" && !args.includes("--no-reinstall")) throw Error("live upgrade update needs --no-reinstall");
  if (cmd === "update" && installed === "prefeature" && !args.includes("--no-restart")) throw Error("the pre-feature build updates only with --no-restart; then run live upgrade kickstart");
}

const uid = () => process.getuid!();
const readRecord = (root: string): UpgradeRecord => JSON.parse(readFileSync(join(root, "record.json"), "utf8"));
const writeRecord = (root: string, value: UpgradeRecord) => atomicWrite(join(root, "record.json"), JSON.stringify(value, null, 2));
const binary = (root: string) => join(root, "bin", "pacer");

async function exec(session: Session, argv: string[], cwd: string, env: Record<string, string | undefined>, check = true) {
  const child = Bun.spawn(argv, { cwd, env, stdin: "ignore", stdout: "pipe", stderr: "pipe" });
  const [code, stdout, stderr] = await Promise.all([child.exited, new Response(child.stdout).text(), new Response(child.stderr).text()]);
  record(session, { kind: "command", argv, code, stdout: stdout.slice(-16000), stderr: stderr.slice(-16000) });
  if (check && code !== 0) throw Error(`${argv.slice(0, 3).join(" ")} exited ${code}: ${stderr.trim()}`);
  return { code, stdout, stderr };
}
function fixtureEnv(r: UpgradeRecord, root: string): Record<string, string | undefined> {
  return { HOME: r.policy.home, PACER_HOME: r.policy.home, PACER_PORT: String(r.policy.port), PACER_BIN: binary(root),
    PACER_RELEASE_BASE: pathToFileURL(join(root, "feed")).href, PACER_NO_UPDATE_CHECK: "1", PACER_BACKEND: "direct", PATH: process.env.PATH, LANG: "C" };
}
function installedBuild(root: string, r: UpgradeRecord): UpgradeBuild {
  const sha = sha256Hex(readFileSync(binary(root)));
  const found = (Object.keys(r.builds) as UpgradeBuild[]).find(name => r.builds[name].sha256 === sha);
  if (!found) throw Error("The installed fixture binary is not one of the recorded builds");
  return found;
}
async function launchctl(session: Session, r: UpgradeRecord, verb: "bootstrap" | "bootout" | "kickstart", check = true) {
  const label = r.policy.serviceLabel;
  if (label === LABEL || !label.startsWith("com.pacer.live.")) throw Error("Refusing a non-fixture service label");
  const target = `gui/${uid()}/${label}`;
  const argv = verb === "bootstrap" ? ["launchctl", "bootstrap", `gui/${uid()}`, join(r.policy.root, "registrations", `${label}.plist`)]
    : verb === "bootout" ? ["launchctl", "bootout", target] : ["launchctl", "kickstart", "-k", target];
  return exec(session, argv, session.root, { PATH: process.env.PATH }, check);
}
async function servicePid(port: number): Promise<number | null> {
  try {
    const r = await fetch(`http://127.0.0.1:${port}/health`, { signal: AbortSignal.timeout(750) });
    const body = await r.json() as { ok?: boolean; pid?: number };
    return r.headers.get("x-pacer") === "1" && body.ok && body.pid ? body.pid : null;
  } catch { return null; }
}
async function waitForPid(port: number, previous: number | null): Promise<number> {
  for (const deadline = Date.now() + 30_000; Date.now() < deadline; await Bun.sleep(250)) {
    const pid = await servicePid(port);
    if (pid && pid !== previous) return pid;
  }
  throw Error("The fixture service did not become healthy within 30 seconds");
}

export async function buildUpgradeFixtures(session: Session): Promise<void> {
  const root = upgradeRoot(session), target = hostTarget();
  if (!target) throw Error("Unsupported platform");
  mkdirSync(root, { mode: 0o700 }); // Exclusive: never reuse a partially built fixture.
  const ota = join(session.root, "ota");
  mkdirSync(ota, { mode: 0o700 }); // Exclusive: never share a lease with live ota.
  for (const dir of [session.root, join(session.root, "home")]) chmodSync(dir, 0o700);
  const policy = upgradePolicy(session, randomBytes(16).toString("hex"), uid());
  atomicWrite(join(ota, "record.json"), JSON.stringify({ schema: 1, phase: "prepared", root: policy.root, nonce: policy.nonce, pacerHome: policy.home,
    innerPort: policy.port, currentApp: policy.currentApp, serviceLabel: policy.serviceLabel, recoveryLabel: policy.recoveryLabel, ownerUid: policy.uid }));
  for (const dir of [join(ota, "registrations"), join(root, "build"), join(root, "bin")]) mkdirSync(dir, { mode: 0o700 });
  const buildEnv = { HOME: process.env.HOME, PATH: process.env.PATH, TMPDIR: process.env.TMPDIR };
  const builds = {} as UpgradeRecord["builds"];
  for (const name of Object.keys(UPGRADE_BUILDS) as UpgradeBuild[]) {
    const { version, ref } = UPGRADE_BUILDS[name];
    let source = checkout;
    if (ref) {
      source = join(root, `source-${version}`);
      await exec(session, ["git", "-C", checkout, "worktree", "add", "--detach", source, ref], checkout, buildEnv);
      await exec(session, ["bun", "install", "--frozen-lockfile"], source, buildEnv);
    }
    const outfile = join(root, "build", `${name}-${version}`);
    await exec(session, [...compileCommand({ root: source, target, version, outfile }), "--define", `PACER_BUILD_OTA_FIXTURE=${JSON.stringify(JSON.stringify(policy))}`], source, buildEnv);
    const bytes = readFileSync(outfile);
    writeFeed(join(root, "feed"), version, bytes);
    builds[name] = { path: outfile, sha256: sha256Hex(bytes) };
  }
  writeRecord(root, { schema: 1, policy, builds, installed: false });
  record(session, { kind: "note", text: `Upgrade fixtures: ${(Object.keys(builds) as UpgradeBuild[]).map(n => `${n} ${UPGRADE_BUILDS[n].version} sha256 ${builds[n].sha256}`).join("; ")}; label ${policy.serviceLabel}` });
}

export async function startUpgradeService(session: Session, build: UpgradeBuild): Promise<void> {
  const root = upgradeRoot(session), r = readRecord(root);
  if (r.installed) throw Error("A fixture service is already registered; run live upgrade cleanup first");
  copyFileSync(r.builds[build].path, binary(root)); chmodSync(binary(root), 0o755);
  writeFileSync(join(r.policy.root, "registrations", `${r.policy.serviceLabel}.plist`), fixturePlist(r.policy, binary(root)), { mode: 0o600 });
  await launchctl(session, r, "bootstrap");
  writeRecord(root, { ...r, installed: true });
  const pid = await waitForPid(r.policy.port, null);
  record(session, { kind: "note", text: `Fixture service ${UPGRADE_BUILDS[build].version} started as ${r.policy.serviceLabel} (pid ${pid})` });
}

export async function upgradePacer(session: Session, args: string[]) {
  const root = upgradeRoot(session), r = readRecord(root);
  if (!r.installed) throw Error("Start a fixture service first: live upgrade start --id <id> --from <build>");
  guardPacerArgs(installedBuild(root, r), args);
  return exec(session, [binary(root), ...args], join(session.root, "repo"), fixtureEnv(r, root), false);
}

/** Scenario upgrade-install: the installed feature build reinstalls its own service (bootout and bootstrap). */
export async function upgradeInstall(session: Session) {
  const root = upgradeRoot(session), r = readRecord(root);
  if (!r.installed || installedBuild(root, r) === "prefeature") throw Error("live upgrade install needs an installed feature build");
  return exec(session, [binary(root), "service", "install"], join(session.root, "repo"), fixtureEnv(r, root), false);
}

/** Restart after a pre-feature `pacer update --no-restart`, as that release's own restart would. */
export async function kickstartUpgradeService(session: Session): Promise<void> {
  const root = upgradeRoot(session), r = readRecord(root);
  if (!r.installed) throw Error("No fixture service is registered");
  const before = await servicePid(r.policy.port);
  await launchctl(session, r, "kickstart");
  record(session, { kind: "note", text: `Fixture service restarted (pid ${before} -> ${await waitForPid(r.policy.port, before)})` });
}

/** Process identities of a task's runner, wrapper or host and agent, or a terminal's host and shell. */
export function upgradeIdentity(session: Session, taskId?: string, terminalId?: string): Record<string, unknown> {
  const root = upgradeRoot(session), r = readRecord(root);
  const pidIn = (dir: string, file: string) => { try { return Number(readFileSync(join(dir, file), "utf8").trim()) || null; } catch { return null; } };
  const of = (pid: number | null | undefined) => pid ? processIdentity(pid) : null;
  let view: Record<string, unknown>;
  if (taskId && /^t-\d{8}-\d{6}-[0-9a-f]{4}$/.test(taskId)) {
    const task = JSON.parse(readFileSync(join(r.policy.home, "tasks", `${taskId}.json`), "utf8")) as { state: string; runnerPid?: number; runnerPacer?: string; handover?: unknown; run?: { dir: string } };
    const dir = task.run?.dir;
    view = { task: taskId, state: task.state, runnerPacer: task.runnerPacer ?? null, handover: task.handover ?? null, runner: of(task.runnerPid),
      wrapperOrHost: dir ? of(pidIn(dir, "pid")) : null, agent: dir ? of(pidIn(dir, "child")) : null,
      sessionVersion: dir && existsSync(join(dir, "session.version")) ? JSON.parse(readFileSync(join(dir, "session.version"), "utf8")) : null };
  } else if (terminalId && /^[0-9a-f-]{36}$/.test(terminalId)) {
    const dir = join(r.policy.home, "terminals", terminalId);
    view = { terminal: terminalId, host: of(pidIn(dir, "pid")), shell: of(pidIn(dir, "child")),
      sessionVersion: existsSync(join(dir, "session.version")) ? JSON.parse(readFileSync(join(dir, "session.version"), "utf8")) : null };
  } else throw Error("identity needs --task <task-id> or --terminal <terminal-id>");
  record(session, { kind: "note", text: `Identity ${JSON.stringify(view)}` });
  return view;
}

export async function cleanupUpgrade(session: Session): Promise<void> {
  const root = upgradeRoot(session), r = readRecord(root);
  if (r.installed) await launchctl(session, r, "bootout", false);
  const prefeature = join(root, `source-${UPGRADE_BUILDS.prefeature.version}`);
  if (existsSync(prefeature)) await exec(session, ["git", "-C", checkout, "worktree", "remove", "--force", prefeature], checkout, { PATH: process.env.PATH }, false);
  writeRecord(root, { ...r, installed: false });
}
