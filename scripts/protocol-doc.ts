import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { opJsonSchemas } from "../src/api/ops";
import { httpStatus, PROTOCOL_VERSION, type ApiErrorCode } from "../src/api/protocol";

/** Deterministic documentation of the v2 transports and registered operation schemas. */
export function renderProtocolDoc(): string {
  const codes: ApiErrorCode[] = [
    "invalid_input", "not_allowed", "unknown_task", "unknown_executor", "unknown_op",
    "conflict", "too_large", "internal",
  ];
  const schemas = opJsonSchemas();
  return [
    "# Client protocol v2",
    "",
    "Generated by `bun run protocol:doc`. Check freshness with `bun scripts/protocol-doc.ts --check`.",
    "",
    "## Overview",
    "",
    `The protocol version is \`${PROTOCOL_VERSION}\` (semver). Clients can use HTTP + SSE from \`pacer serve\`, or line-delimited JSON-RPC 2.0 over stdio from \`pacer api --stdio\` without a daemon. Both transports call the same operation registry.`,
    "",
    "HTTP binds to `127.0.0.1` only. Every `/v2/*` route requires `Authorization: Bearer <token>`; the server token file has permissions `0600`. Operation request bodies are capped at 256 KiB in UTF-8 bytes; larger bodies return `413 too_large`. Operations use POST, and all other routes use GET.",
    "",
    "Additive fields do not bump the protocol version. Clients must ignore unknown fields and event types. Removing or renaming fields requires a major version bump; the previous major is served for one pacer minor release.",
    "",
    "Operation inputs are validated. No operation runs free text in a shell. `task.delegate` and `task.retry` refuse calls when the API process itself is an executor session.",
    "",
    "## Errors",
    "",
    'HTTP route errors after authentication use `{ "error": { "code": "...", "message": "...", "hint": "..." } }`; `hint` is optional.',
    "",
    "| Code | HTTP status |",
    "|---|---|",
    ...codes.map((code) => `| \`${code}\` | ${httpStatus(code)} |`),
    "",
    "Missing or invalid HTTP tokens return 401 with the plain-text body `unauthorized`. A wrong HTTP verb returns 405 with `invalid_input`.",
    "",
    "JSON-RPC errors use `{ jsonrpc: \"2.0\", id, error: { code, message, data? } }`:",
    "",
    "| Failure | JSON-RPC code | Data |",
    "|---|---|---|",
    "| Invalid JSON | -32700 | Omitted; response id is null |",
    "| Invalid request envelope | -32600 | Omitted; response id is null |",
    "| Unknown method | -32601 | `{ code: \"unknown_op\", hint? }` |",
    "| Invalid params | -32602 | `{ code: \"invalid_input\", hint? }` |",
    "| Other core or internal error | -32000 | `{ code, hint? }` |",
    "",
    "## HTTP routes",
    "",
    "| Route | Response |",
    "|---|---|",
    "| `GET /v2/hello` | `{ protocol, pacer, ops, events }`: protocol and pacer versions, operation names and event types |",
    "| `GET /v2/snapshot` | `{ protocol, seq, snapshot }`: current snapshot and its sequence number |",
    "| `GET /v2/events?since=<seq>` | SSE events after `since` (default 0); `Last-Event-ID` overrides the query parameter |",
    "| `POST /v2/ops/<name>` | JSON params body; success is `200 { result }`, errors use the table above |",
    "| `GET /v2/tasks/<id>/log?follow=1` | SSE `log` events with `{ stdout, stderr }`, starting at byte offset 0; ends with `done` and `{}` after completion |",
    "",
    "Event cursors must be non-negative safe integers. Read a task's diff through `task.diff` using the operation route.",
    "",
    "## JSON-RPC methods",
    "",
    "Send one JSON object per line. Requests use `{ jsonrpc: \"2.0\", id, method, params? }`; success replies use `{ jsonrpc: \"2.0\", id, result }`. Requests run concurrently, so clients must match replies by id. Valid notifications (requests without an id) receive no reply.",
    "",
    "| Method | Params | Result |",
    "|---|---|---|",
    "| `hello` | None | Same hello object as HTTP |",
    "| `snapshot` | None | Same snapshot object as HTTP |",
    "| `subscribe` | `{ since?: number }`, default 0, a non-negative safe integer | `{ subscribed: true, last }`, then `event` notifications |",
    "| Any operation name below | Its params schema | The operation result directly |",
    "",
    "Subscription notifications use `{ jsonrpc: \"2.0\", method: \"event\", params: { seq, at, type, data } }`. A new subscription replaces the previous cursor. When input ends, event polling stops and pending requests finish.",
    "",
    "## Events",
    "",
    "The advertised v2 event types are `budget`, `task`, `mode`, `alert` and `reset`. Events have `{ seq, at, type, data }`; `seq` is the resume cursor, `at` is the context time, and `data` carries the event payload.",
    "",
    "HTTP SSE frames carry the sequence number as `id`, the type as `event`, and the JSON payload as `data`:",
    "",
    "```text",
    "id: <seq>",
    "event: <type>",
    "data: <JSON payload>",
    "",
    "```",
    "",
    "Frames end with a blank line. Streams poll every second by default and send a `: keepalive` comment every 15 seconds. JSON-RPC subscriptions poll every 500 ms by default.",
    "",
    "The outbox retains the last 200 entries. If a positive resume cursor predates the retained entries, a single `reset` event precedes the retained events. Its sequence is one less than the oldest retained entry, and its data is `{ reason: \"events were dropped; fetch the snapshot again\" }`. Fetch `/v2/snapshot` (or call `snapshot`) again and resume from its sequence to recover the full state.",
    "",
    "## Operations",
    "",
    ...Object.entries(schemas).flatMap(([name, def]) => [
      `### \`${name}\``, "", def.description, "", "Params JSON Schema:", "",
      "```json", JSON.stringify(def.params, null, 2), "```", "",
    ]),
    "## Clients",
    "",
    "TypeScript clients in this repository use `ApiClient` from `src/api/client.ts`. `connectClient` picks HTTP when `pacer serve` answers `/health` with `X-Pacer: 1`, and otherwise runs in-process. `PACER_API=inprocess` forces in-process.",
    "",
    "The Orca plugin worker reads the v2 API over HTTP when `pacer serve` is running, otherwise through a `pacer api --stdio` child; panel commands still reach the console terminal, which executes mapped commands as v2 operations.",
    "",
    "HTTP `subscribe` reconnects with `Last-Event-ID` to resume from the last seen event.",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const path = join(import.meta.dir, "..", "docs", "protocol.md");
  const doc = renderProtocolDoc();
  if (process.argv.includes("--check")) {
    let existing: string | undefined;
    try { existing = readFileSync(path, "utf8"); }
    catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
    if (existing !== doc) {
      console.error("docs/protocol.md is out of date; run `bun run protocol:doc`");
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, doc);
  }
}
