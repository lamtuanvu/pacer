if (import.meta.main) {
  const path = join(import.meta.dir, "..", "docs", "protocol.md");
  const doc = renderProtocolDoc();
  if (process.argv.includes("--check")) {
    let existing: string | undefined;
    try { existing = readFileSync(path, "utf8"); }
    catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
    if (existing !== doc) {
      console.error("docs/protocol.md is out of date; run `bun run protocol:doc`");
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, doc);
  }
}
