import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { clientProtocolSchema } from "../scripts/protocol-doc";
import { opJsonSchemas } from "../src/api/ops";

const root = join(import.meta.dir, "..");
test("docs/protocol.schema.json is generated from the operation registry", () => {
  expect(readFileSync(join(root, "docs/protocol.schema.json"), "utf8"))
    .toBe(JSON.stringify(clientProtocolSchema(), null, 2) + "\n");
});

test("every operation has a Params definition", () => {
  const defs = (clientProtocolSchema() as { $defs: Record<string, unknown> }).$defs;
  for (const [name, schema] of Object.entries(opJsonSchemas())) {
    const pascal = name.split(/[._]/).map(s => s[0]!.toUpperCase() + s.slice(1)).join("");
    expect(defs[`${pascal}Params`]).toBeDefined();
    expect(JSON.stringify(defs[`${pascal}Params`])).not.toContain('"$schema"');
  }
  const refs = [...JSON.stringify(defs).matchAll(/"\$ref":"#\/\$defs\/([^"]+)"/g)].map(m => m[1]!);
  expect(refs.filter(r => !(r in defs))).toEqual([]);
  expect(defs.TaskDelegateParams).toBeDefined();
  expect(defs.ApiError).toBeDefined();
  expect(defs.Hello).toBeDefined();
});

test("generated Rust files exist for both schemas", () => {
  for (const file of ["crates/client-protocol/src/generated.rs", "crates/plugin-protocol/src/generated.rs"]) {
    expect(readFileSync(join(root, file), "utf8").startsWith("// @generated by cargo xtask gen.")).toBe(true);
  }
});
