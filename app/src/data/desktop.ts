import { platform, createPlatform, type DesktopHost } from '../platform';
export { desktopHost } from '../platform';
export type { DesktopHost, DesktopUpdateConnection, WindowControls } from '../platform';
const adapter = (host?: DesktopHost) => host === undefined ? platform : createPlatform(host);
export const readRoundedWindowSupport = (host?: DesktopHost) => adapter(host).readRoundedWindowSupport();
export const readNativeTitlebarSupport = (host?: DesktopHost) => adapter(host).readNativeTitlebarSupport();
export const readDesktopVersion = (host?: DesktopHost) => adapter(host).readDesktopVersion();
export const readDesktopUpdateConnection = (host?: DesktopHost) => adapter(host).readDesktopUpdateConnection();
export const openDesktopTakeover = (host?: DesktopHost) => adapter(host).openDesktopTakeover();
export const windowControls = (host?: DesktopHost) => adapter(host).windowControls;
export const isDesktop = (host?: DesktopHost) => adapter(host).desktop;
