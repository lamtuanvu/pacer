import { readFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";

/** Build-time only: the design system's tokens.json, merged with app-side provisional entries, becomes tokens.css and tokens.ts. */
const colorToken = z.looseObject({ name: z.string().min(1), value: z.object({ light: z.string().min(1), dark: z.string().min(1) }), usage: z.string().optional() });
const valueToken = z.looseObject({ name: z.string().min(1), value: z.string().min(1), usage: z.string().optional() });
const typeStyle = z.looseObject({ name: z.string().min(1), fontSize: z.string(), lineHeight: z.string(), fontWeight: z.number(), letterSpacing: z.string().optional() });
export const tokenFileSchema = z.looseObject({
  name: z.string(),
  version: z.number(),
  color: z.looseObject({ themes: z.array(z.looseObject({ id: z.string(), name: z.string() })), tokens: z.array(colorToken) }),
  type: z.looseObject({ families: z.record(z.string(), z.string()), groups: z.array(z.looseObject({ name: z.string(), styles: z.array(typeStyle) })) }),
  spacing: z.looseObject({ tokens: z.array(valueToken) }),
  radius: z.looseObject({ tokens: z.array(valueToken) }),
  size: z.looseObject({ tokens: z.array(valueToken) }),
  shadow: z.looseObject({ tokens: z.array(valueToken) }),
  layer: z.looseObject({ tokens: z.array(valueToken) }),
  motion: z.looseObject({ tokens: z.array(valueToken) }),

});
export type TokenFile = z.infer<typeof tokenFileSchema>;
type Provisional = { provisional: string };
export interface LocalTokenFile {
  color?: { tokens: (z.infer<typeof colorToken> & Provisional)[] };
  spacing?: { tokens: (z.infer<typeof valueToken> & Provisional)[] };
  radius?: { tokens: (z.infer<typeof valueToken> & Provisional)[] };
  size?: { tokens: (z.infer<typeof valueToken> & Provisional)[] };
  shadow?: { tokens: (z.infer<typeof valueToken> & Provisional)[] };
  layer?: { tokens: (z.infer<typeof valueToken> & Provisional)[] };
  motion?: { tokens: (z.infer<typeof valueToken> & Provisional)[] };

}
const GROUPS = ["color", "spacing", "radius", "size", "shadow", "layer", "motion"] as const;

/** Provisional entries are for tokens the design system lacks; one it now has must be removed here. */
export function mergeTokens(base: TokenFile, local: LocalTokenFile): TokenFile {
  const merged = structuredClone(base);
  for (const group of GROUPS) {
    const extra = local[group]?.tokens ?? [];
    const names = new Set(base[group].tokens.map(t => t.name));
    for (const token of extra) if (names.has(token.name)) throw new Error(`${token.name} is now in the design system; remove it from tokens.local.json`);
    (merged[group].tokens as unknown[]).push(...extra);
  }
  return merged;
}
export function provisionalEntries(local: LocalTokenFile): { group: string; name: string; provisional: string }[] {
  return GROUPS.flatMap(group => (local[group]?.tokens ?? []).map(t => ({ group, name: t.name, provisional: t.provisional })));
}

/** Escapes token names such as space-1.5. */
export function generateTokensCss(tokens: TokenFile): string {
  const variable = (name: string, value: string | number) => `  --${name.replaceAll(".", "\\.")}: ${value};`;
  const colors = (theme: "light" | "dark") => tokens.color.tokens.map(t => variable(t.name, t.value[theme])).join("\n");
  const type = tokens.type.groups.flatMap(g => g.styles.flatMap(s => [
    variable(`type-${s.name}-size`, s.fontSize), variable(`type-${s.name}-line`, s.lineHeight), variable(`type-${s.name}-weight`, s.fontWeight),
    ...(s.letterSpacing !== undefined ? [variable(`type-${s.name}-tracking`, s.letterSpacing)] : []),
  ]));
  return `/* Generated from tokens.json. */\n:root {\n  color-scheme: light dark;\n${colors("light")}\n${[
    ...Object.entries(tokens.type.families).map(([name, value]) => variable(`font-${name}`, value)), ...type,
    ...GROUPS.filter(group => group !== "color").flatMap(group => tokens[group].tokens.map(t => variable(t.name, t.value))),
  ].join("\n")}\n  font-variant-numeric: tabular-nums;\n}\n@media (prefers-color-scheme: dark) {\n:root:not([data-theme="light"]) {\n${colors("dark")}\n}\n}\n:root[data-theme="dark"] {\n${colors("dark")}\n}\n`;
}
export function generateTokensTs(tokens: TokenFile): string {
  const names = tokens.color.tokens.map(t => JSON.stringify(t.name));
  const entries = tokens.color.tokens.map(t => `  ${JSON.stringify(t.name)}: { light: ${JSON.stringify(t.value.light)}, dark: ${JSON.stringify(t.value.dark)} },`);
  return `// Generated by app/tokens-gen.ts. Do not edit.\nexport type ColorToken =\n  | ${names.join("\n  | ")};\nexport const colorTokens: Record<ColorToken, { light: string; dark: string }> = {\n${entries.join("\n")}\n};\n`;
}

export function readTokens(dir: string): TokenFile {
  const base = tokenFileSchema.parse(JSON.parse(readFileSync(join(dir, "tokens.json"), "utf8")));
  const local = JSON.parse(readFileSync(join(dir, "tokens.local.json"), "utf8")) as LocalTokenFile;
  return mergeTokens(base, local);
}
