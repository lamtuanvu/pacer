import { pluginManifest } from "./src/manifest";
import { renderPanel } from "./src/panel";
import { emptySnapshot } from "../src/link/envelope";
import pkg from "../package.json";
export async function buildPluginAssets(version: string): Promise<{ manifest: string; worker: string; panel: string; mark: string; generated: string }> {
  const result = await Bun.build({ entrypoints: [new URL("./src/worker.ts", import.meta.url).pathname], target: "node", format: "esm", minify: false });
  if (!result.success) throw new AggregateError(result.logs, "pacer plugin build failed");
  const worker = await result.outputs[0].text();
  const manifest = `${JSON.stringify(pluginManifest(version), null, 2)}\n`;
  const panel = renderPanel(emptySnapshot(), { nowS: 0, transport: null, reachable: false });
  const mark = await Bun.file(new URL("./assets/pacer-mark.svg", import.meta.url)).text();
  const files = [{ rel: "assets/pacer-mark.svg", text: mark },{ rel: "orca-plugin.json", text: manifest }, { rel: "worker.mjs", text: worker }];
  const generated = `// generated by \`bun run plugin:build\`; do not edit\nexport const PLUGIN_VERSION = ${JSON.stringify(version)};\nexport const PLUGIN_FILES: { rel: string; text: string }[] = ${JSON.stringify(files, null, 2)};\nexport const PANEL_PLACEHOLDER: string = ${JSON.stringify(panel)};\n`;
  return { manifest, worker, panel, mark, generated };
}
if (import.meta.main) {
  const assets = await buildPluginAssets(pkg.version);
  await Bun.write(new URL("./dist/assets/pacer-mark.svg", import.meta.url), assets.mark);
  await Bun.write(new URL("./dist/worker.mjs", import.meta.url), assets.worker);
  await Bun.write(new URL("./dist/orca-plugin.json", import.meta.url), assets.manifest);
  await Bun.write(new URL("./dist/panel/live.html", import.meta.url), assets.panel);
  await Bun.write(new URL("../src/plugin/assets.generated.ts", import.meta.url), assets.generated);
}
